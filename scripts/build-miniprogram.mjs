#!/usr/bin/env node
/**
 * Build the WeChat mini-program's vendored assets from the single source of truth:
 *   1. compile the pure-TS engine + utils → miniprogram/lib/ (CommonJS) via tsc
 *   2. vendor seedrandom + rewrite rng.js's require to the local copy
 *   3. emit every model JSON as a CommonJS module + a manifest + a static
 *      slug→loader map (mini-programs can't fetch local files, and dynamic
 *      require paths are unreliable — so we generate static requires)
 *
 * Re-run after any engine change or model rebuild:
 *   node scripts/build-miniprogram.mjs
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MP = join(ROOT, 'miniprogram');
const MODELS = join(ROOT, 'web/public/models/tracks/2025');

// 1. Compile the engine to CommonJS.
console.log('[mp] compiling engine → miniprogram/lib …');
execSync('npx tsc -p tsconfig.miniprogram.json', { cwd: join(ROOT, 'web'), stdio: 'inherit' });

// 2. Vendor seedrandom + point rng.js at it (so there's no npm-build step).
copyFileSync(join(ROOT, 'web/node_modules/seedrandom/seedrandom.min.js'), join(MP, 'lib/engine/seedrandom.js'));
const rngPath = join(MP, 'lib/engine/rng.js');
writeFileSync(rngPath, readFileSync(rngPath, 'utf8').replace('require("seedrandom")', 'require("./seedrandom.js")'));
console.log('[mp] vendored seedrandom');

// 3. Emit model data as CommonJS modules + manifest + static loader map.
const dataDir = join(MP, 'data');
const tracksDir = join(dataDir, 'tracks');
rmSync(tracksDir, { recursive: true, force: true });
mkdirSync(tracksDir, { recursive: true });

const slugs = readdirSync(MODELS).filter((f) => f.endsWith('.json') && f !== 'index.json').map((f) => f.replace('.json', ''));
let totalKb = 0;
for (const slug of slugs) {
  const raw = readFileSync(join(MODELS, `${slug}.json`), 'utf8');
  JSON.parse(raw); // fail loudly on invalid JSON (e.g. a NaN) before it reaches the app
  writeFileSync(join(tracksDir, `${slug}.js`), `module.exports = ${raw};\n`);
  totalKb += Buffer.byteLength(raw) / 1024;
}
const manifest = readFileSync(join(MODELS, 'index.json'), 'utf8');
JSON.parse(manifest);
writeFileSync(join(dataDir, 'manifest.js'), `module.exports = ${manifest};\n`);

const loaders = slugs.map((s) => `  '${s}': () => require('./tracks/${s}.js'),`).join('\n');
writeFileSync(join(dataDir, 'index.js'),
  `// Generated by scripts/build-miniprogram.mjs — do not edit.\n` +
  `module.exports = {\n  manifest: require('./manifest.js'),\n  loaders: {\n${loaders}\n  },\n};\n`);

console.log(`[mp] wrote ${slugs.length} model modules + manifest + loader map (${Math.round(totalKb)} KB data)`);
console.log('[mp] done. Open ./miniprogram in WeChat DevTools.');
